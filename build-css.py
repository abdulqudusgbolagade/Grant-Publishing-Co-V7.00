#!/usr/bin/env python3
"""Expand assets/v7.src.css into assets/v7.css.

"@@" becomes a high-specificity .gpc-site prefix, and declarations inside rules
that use it are marked !important so the design layer wins over the 6.x themes.
Run: python3 tools/build-css.py
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "v7.src.css"
OUT = ROOT / "assets" / "v7.css"
PREFIX = "html body .gpc-site.gpc-site.gpc-site.gpc-site.gpc-site.gpc-site"


def important(body: str) -> str:
    out = []
    for decl in re.split(r";(?![^(]*\))", body):
        d = decl.strip()
        if not d:
            continue
        prop = d.split(":", 1)[0].strip()
        if prop.startswith("--") or "!important" in d:
            out.append(d)
        else:
            out.append(d + " !important")
    return "; ".join(out) + ";"


def expand(css: str) -> str:
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    res, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            res.append(css[i:])
            break
        sel = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            depth += {"{": 1, "}": -1}.get(css[k], 0)
            k += 1
        body = css[j + 1:k - 1]
        if sel.startswith("@media"):
            res.append(f"{sel} {{\n{expand(body)}\n}}\n")
        elif sel.startswith("@keyframes"):
            res.append(f"{sel} {{{body}}}\n")
        else:
            if "@@" in sel:
                sel = sel.replace("@@", PREFIX)
                body = important(body)
            res.append(f"{sel} {{ {body.strip()} }}\n")
        i = k
    return "".join(res)


if __name__ == "__main__":
    text = expand(SRC.read_text())
    OUT.write_text("/* Grant Publishing Co. 7.0 design layer. Generated by tools/build-css.py from assets/v7.src.css. */\n" + text)
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
